import { test, expect } from '@playwright/test';
import { login } from './helpers';
test('后台证据、建议审核和验证关闭', async ({ page }) => {
  test.setTimeout(90000);
  await login(page);
  await page.getByRole('tab', { name: '统计与改进' }).click();
  await page.getByRole('button', { name: '生成改进建议草稿' }).click();
  await expect(page.getByText('改进任务详情', { exact: true })).toBeVisible();
  await page.getByLabel('处理原因', { exact: true }).fill('依据快照检查，批准模拟改进');
  await page.getByLabel('负责人', { exact: true }).click();
  await page.getByText('admin · ADMIN', { exact: true }).click();
  await page.getByLabel('执行计划', { exact: true }).fill('复核费用说明，保留处理记录');
  await page.getByLabel('验证目标', { exact: true }).fill('比较相同口径的样本，结果不足时明确说明');
  await page.getByRole('button', { name: '保存任务进展' }).click();
  await expect(page.getByTestId('improvement-status')).toHaveText('已审核');
  await page.getByLabel('处理原因', { exact: true }).fill('开始执行已审核计划');
  await page.getByRole('button', { name: '保存任务进展' }).click();
  await expect(page.getByLabel('同期条件变化', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '生成新统计快照' }).click();
  await page.getByLabel('处理原因', { exact: true }).fill('模拟验证完成');
  await page.getByLabel('同期条件变化', { exact: true }).fill('同一模拟环境，没有真实业务样本');
  await page.getByLabel('验证结论（含未改善情况）', { exact: true }).fill('样本不足，不认定改进效果');
  await page.getByLabel('遗留问题', { exact: true }).fill('后续需要真实授权评测');
  await page.getByRole('button', { name: '保存任务进展' }).click();
  await expect(page.getByText('验证记录', { exact: true })).toBeVisible();
  await page.getByLabel('处理原因', { exact: true }).fill('证据已留存，关闭模拟任务');
  await page.getByRole('button', { name: '保存任务进展' }).click();
  await expect(page.getByRole('button', { name: '保存任务进展' })).toHaveCount(0);
  await page.getByRole('tab', { name: '评测记录' }).click();
  await expect(page.getByText('版本评测批次', { exact: true })).toBeVisible();
  await page.getByRole('tab', { name: '提示词与运行' }).click();
  await expect(page.getByText('提示词版本', { exact: true })).toBeVisible();
  await page.getByRole('tab', { name: '资料管理' }).click();
  await page.getByLabel('选择产品', { exact: true }).click();
  await page.getByText('融合89 · PACKAGE', { exact: true }).click();
  await expect(page.getByRole('button', { name: '已发布不可覆盖' }).first()).toBeVisible();
  await page.getByRole('tab', { name: '文本质检' }).click();
  await page.getByLabel('查询政策所属产品', { exact: true }).click();
  await page.getByText('融合89', { exact: true }).click();
  await page.getByLabel('政策版本依据', { exact: true }).click();
  await page.getByText('V1 · 已发布', { exact: true }).click();
  await page.getByLabel('待检查正文', { exact: true }).fill('月费59元，合约12个月。');
  await page.getByRole('button', { name: '执行文本质检' }).click();
  await expect(page.getByText('文案月费与政策不符', { exact: true })).toBeVisible();
  await page.getByLabel('复核决定', { exact: true }).click();
  await page.getByText('修订重检', { exact: true }).click();
  await page.getByLabel('复核原因', { exact: true }).fill('根据已发布政策修正月费');
  await page.getByLabel('修订稿（选择修订时必填）', { exact: true }).fill('月费89元，一次费0元，合约12个月。');
  await page.getByRole('button', { name: '保存人工复核' }).click();
  await expect(page.getByTestId('quality-status')).toHaveText('需要人工复核');
  await expect(page.getByRole('cell', { name: '月费89元，一次费0元，合约12个月。', exact: true }).first()).toBeVisible();
  await page.screenshot({ path: '../.local/e2e-admin-pages.png', fullPage: true });
});
