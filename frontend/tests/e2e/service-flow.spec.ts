import { test, expect } from '@playwright/test';
import { fixture, login, query, recommendAndSubmit } from './helpers';
test('取号到办理、评价和后台关联记录', async ({ page, context }) => {
  test.setTimeout(90000);
  const account = fixture();
  const publicPage = await context.newPage();
  await publicPage.goto('/take-number');
  await publicPage.getByRole('button', { name: '领取号码' }).click();
  const ticket = await publicPage.getByRole('heading', { name: /您的号码/ }).textContent();
  await login(page);
  await page.getByRole('tab', { name: '排队与窗口' }).click();
  await page.getByRole('button', { name: '叫下一号 · 1号窗口', exact: true }).click();
  const row = page.getByRole('row').filter({ hasText: ticket!.split('：')[1] });
  await row.getByRole('button', { name: '开始接待' }).click();
  await query(page, account.number);
  await recommendAndSubmit(page);
  await expect(page.getByTestId('acceptance-status')).toHaveText('办理成功');
  await page.getByRole('button', { name: '结束接待', exact: true }).click();
  await page.getByRole('button', { name: '生成客户评价链接' }).click();
  const popup = context.waitForEvent('page');
  await page.getByRole('link', { name: '打开本次服务评价页' }).click();
  const feedback = await popup;
  await feedback.getByLabel('满意度', { exact: true }).click();
  await feedback.getByText('5 分', { exact: true }).click();
  await feedback.getByRole('textbox', { name: /意见/ }).fill('解释清晰，已了解新合约');
  await feedback.getByRole('button', { name: '提交评价' }).click();
  await expect(feedback.getByText('评价已提交，感谢反馈。')).toBeVisible();
  await page.getByRole('button', { name: '刷新评价' }).click();
  await expect(page.getByText(/5 分 ·.*解释清晰/)).toBeVisible();
  const sid = new URL(page.url()).searchParams.get('id');
  await page.getByRole('tab', { name: '统计与改进' }).click();
  const metrics = await page.request.get('/api/v1/service-metrics');
  const data = await metrics.json();
  expect(data.evidence.service_ids).toContain(sid);
  expect(data.metrics.satisfaction.sample_count).toBeGreaterThan(0);
  await page.screenshot({ path: '../.local/e2e-service-flow.png', fullPage: true });
});
